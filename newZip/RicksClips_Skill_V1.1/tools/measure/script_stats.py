"""Per-episode script statistics -> references/reports/script_stats.md.

Reads references/scripts/*.txt (raw transcripts), pairs each with its video in
"references/video references" for the duration, and measures the formula claims:
words/s, hook length, "You see" position, sentence lengths, question count.
"""
import re, glob, os, subprocess, statistics

BASE = os.path.join(os.path.dirname(__file__), "..", "..", "references")
VIDDIR = os.path.join(BASE, "video references")

def duration(title):
    for f in glob.glob(os.path.join(VIDDIR, "*.mp4")):
        if os.path.basename(f).startswith(title):
            r = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration",
                                "-of", "csv=p=0", f], capture_output=True, text=True)
            return float(r.stdout.strip())
    return None

rows, wps_list, hook_list, ys_pos = [], [], [], []
for path in sorted(glob.glob(os.path.join(BASE, "scripts", "*.txt"))):
    title = os.path.splitext(os.path.basename(path))[0]
    if title == "README":
        continue
    txt = open(path, encoding="utf-8", errors="replace").read()
    txt = re.sub(r"\[(music|applause|laughter)\]", " ", txt, flags=re.I)
    txt = re.sub(r"\s+", " ", txt).strip()
    words = txt.split()
    n = len(words)
    sents = [s.strip() for s in re.split(r"(?<=[.!?])\s+", txt) if s.strip()]
    hook = len(sents[0].split()) if sents else 0
    m = re.search(r"\byou see\b", txt, re.I)
    pos = round(100 * len(txt[: m.start()].split()) / n, 1) if m else None
    qs = txt.count("?")
    dur = duration(title)
    wps = round(n / dur, 2) if dur else None
    slen = round(statistics.median(len(s.split()) for s in sents), 1) if sents else 0
    rows.append((title, n, dur, wps, hook, pos, slen, qs))
    if wps: wps_list.append(wps)
    hook_list.append(hook)
    if pos: ys_pos.append(pos)

out = ["# Script statistics, measured per episode (generated by tools/measure/script_stats.py)",
       "",
       "Raw transcripts in references/scripts/ (auto-transcribed; [music] tags stripped).",
       "Duration from the video file; wps = words / duration. 'You see %' = word position of",
       "the pivot as a share of total words (proxy for time position).",
       "",
       "| Episode | words | dur s | w/s | hook words | 'You see' at % | sent. median | ?s |",
       "|---|---|---|---|---|---|---|---|"]
for r in rows:
    out.append("| " + " | ".join(str(v) if v is not None else "—" for v in r) + " |")

def med(v): return round(statistics.median(v), 2) if v else None
out += ["",
        "## Aggregates",
        f"- words/s: median **{med(wps_list)}**, range {min(wps_list)}–{max(wps_list)} (STYLE_BIBLE claim: 3.5–4.1, median 3.7)",
        f"- hook length: median **{med(hook_list)}** words, range {min(hook_list)}–{max(hook_list)} (claim: 10–16)",
        f"- 'You see' present in **{len(ys_pos)}/{len(rows)}** scripts (claim: 14/20), median position **{med(ys_pos)} %** of words",
        "",
        "Use for OUR scripts: hook inside the claimed band; place the pivot at the measured median position;",
        "keep w/s 3.5–4.1 when timing the voice.",
        ]
dest = os.path.join(BASE, "reports", "script_stats.md")
open(dest, "w", encoding="utf-8").write("\n".join(out) + "\n")
print("\n".join(out[-6:]))
print("written:", dest)
